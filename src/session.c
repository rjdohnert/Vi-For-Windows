#include "vi.h"
#include "session.h"
#include "buffer.h"
#include "ex.h"
#include "syntax.h"
#include "screen.h"

bool session_save(const char *path) {
    const char *target = (path && *path) ? path : "Session.vim";
    FILE *fp = fopen(target, "w");
    if (!fp) {
        set_status("E484: Cannot open session file for writing: %s", target);
        return false;
    }

    fprintf(fp, "\" Vi 5.0.0-2026 Session File\n");
    fprintf(fp, "\" Automatically generated by :mksession\n\n");

    /* 1. Add all buffers */
    for (int i = 0; i < E.num_buffers; i++) {
        if (E.buffers[i].filename && E.buffers[i].filename[0] != '[') {
            fprintf(fp, "badd %s\n", E.buffers[i].filename);
        }
    }

    /* 2. Current buffer and cursor position */
    if (E.filename && E.filename[0] != '[') {
        fprintf(fp, "edit %s\n", E.filename);
        fprintf(fp, "%d\n", E.cy + 1);
    }

    /* 3. Editor options */
    fprintf(fp, "set %snumber\n", E.opt.number ? "" : "no");
    fprintf(fp, "set %swrap\n", E.opt.wrap ? "" : "no");
    fprintf(fp, "set %signorecase\n", E.opt.ignorecase ? "" : "no");
    fprintf(fp, "set %sautoindent\n", E.opt.autoindent ? "" : "no");
    fprintf(fp, "set %shlsearch\n", E.opt.hlsearch ? "" : "no");
    fprintf(fp, "set %sincsearch\n", E.opt.incsearch ? "" : "no");
    fprintf(fp, "set %sautoread\n", E.opt.autoread ? "" : "no");
    fprintf(fp, "set %sundofile\n", E.opt.undofile ? "" : "no");
    fprintf(fp, "set tabstop=%d\n", E.opt.tabstop);
    fprintf(fp, "set shiftwidth=%d\n", E.opt.shiftwidth);
    if (E.opt.foldmethod[0]) {
        fprintf(fp, "set fdm=%s\n", E.opt.foldmethod);
    }
    fprintf(fp, "colorscheme %s\n", syntax_get_colorscheme());

    fclose(fp);
    set_status("Session saved to \"%s\"", target);
    return true;
}

bool session_load(const char *path) {
    const char *target = (path && *path) ? path : "Session.vim";
    FILE *fp = fopen(target, "r");
    if (!fp) {
        set_status("E484: Cannot open session file: %s", target);
        return false;
    }

    char line[512];
    while (fgets(line, sizeof(line), fp)) {
        int len = (int)strlen(line);
        while (len > 0 && (line[len - 1] == '\r' || line[len - 1] == '\n')) line[--len] = '\0';
        if (len == 0 || line[0] == '"') continue;

        execute_ex_command(line);
    }
    fclose(fp);
    set_status("Session loaded from \"%s\"", target);
    return true;
}
